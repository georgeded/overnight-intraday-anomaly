import sys

import numpy as np
import pandas as pd

from checks import flag_panel
from config import END, SAMPLES, md_table, write_report
from data_layer import NYSE, load_prices, load_rf, save_processed

def sample_of(dates):
    out = pd.Series("", index=dates.index)
    for name, (a, b) in SAMPLES.items():
        out[(dates >= a) & (dates <= b)] = name
    return out

def build(source="crsp"):
    px = load_prices(source)
    df = flag_panel(px[px["date"] <= END]).drop(columns=["prev_close"])

    # rf from each session's previous close, rf_days is the calendar days it covers
    sessions = NYSE.sessions_in_range(df["date"].min() - pd.Timedelta(days=10), END)
    rf = pd.DataFrame({"date": sessions, "rf_days": sessions.to_series().diff().dt.days.to_numpy(),
                       "rf": load_rf().reindex(sessions).to_numpy()})
    df = df.merge(rf, on="date", how="left")
    df.loc[df["flag_first_row"], ["rf", "rf_days"]] = np.nan

    # the whole day's rf sits on the overnight leg
    df["rf_overnight"] = df["rf"]
    df["rf_intraday"] = np.where(df["flag_first_row"], np.nan, 0.0)
    df["overnight_xs"] = df["overnight"] - df["rf_overnight"]
    df["intraday_xs"] = df["intraday"] - df["rf_intraday"]
    df["sample"] = sample_of(df["date"])
    return df

def checks(df):
    d = df[~df["flag_first_row"]].copy()
    d["prev_close"] = d.groupby("ticker")["close"].shift()
    both = d["overnight"].notna() & d["intraday"].notna()
    plain = ~d["flag_ex_div"] & ~d["flag_split"]

    rows = []
    for t, g in d.groupby("ticker"):
        gb = g[both.loc[g.index]]
        cum = {s: (1 + x["overnight"]).prod() * (1 + x["intraday"]).prod() / (1 + x["ret"]).prod() - 1
               for s, x in gb.groupby("sample")}
        gap = (g["overnight"] - (g["open"] / g["prev_close"] - 1))[plain.loc[g.index]].abs()
        rows.append({"ticker": t, "days": len(g), "days_with_both_legs": len(gb),
                     "identity_max_error": ((1 + gb["overnight"]) * (1 + gb["intraday"]) - (1 + gb["ret"])).abs().max(),
                     "cumulative_max_error": max(abs(v) for v in cum.values()),
                     "overnight_vs_open_max_error": gap.max(),
                     "rf_missing": int(g["rf"].isna().sum())})
    return pd.DataFrame(rows)

def hand_checks(df):
    d = df.assign(prev_close=df.groupby("ticker")["close"].shift())
    picks = []
    for t in ["SPY", "QQQ", "IWM"]:
        ex = d[(d["ticker"] == t) & d["flag_ex_div"] & (d["sample"] != "test")]
        picks += [ex.index[0], ex.index[-1]]
    h = d.loc[picks + list(d.index[d["flag_split"]])]

    ret_by_hand = (h["close"] + h["dividend"]) * h["split_factor"] / h["prev_close"] - 1
    return pd.DataFrame({"date": h["date"].dt.date, "ticker": h["ticker"], "dividend": h["dividend"],
                         "split": h["split_factor"], "ret": h["ret"], "ret_by_hand": ret_by_hand,
                         "overnight": h["overnight"],
                         "overnight_by_hand": (1 + ret_by_hand) / (h["close"] / h["open"]) - 1})

def report(source="crsp"):
    df = build(source)
    path = save_processed(df, f"returns_{source}")
    counts = df.groupby("sample")["ticker"].value_counts().unstack().loc[["train", "validation", "test"]]
    weekend = df.groupby(df["rf_days"].clip(upper=4))["rf"].mean().mul(1e4).rename("mean_rf_bp")

    out = [f"# Step 3: returns ({source})", "",
           f"Generated by `python src/returns.py {source}`, {len(df)} rows saved to `data/processed/{path.name}`.", "",
           "## Definitions", "",
           "- `ret`: CRSP close-to-close total return",
           "- `intraday = close / open - 1`",
           "- `overnight = (1 + ret) / (close / open) - 1`, previous close to open, so dividends and splits sit here",
           "- `rf`: 3-month T-bill converted to a return from the previous close, all of it on the overnight leg",
           "- `overnight_xs = overnight - rf`, `intraday_xs = intraday`",
           "- Samples: train 1993-2012, validation 2013-2018, test 2019-2025", "",
           'The multiplicative split is an approximation on dividend days: its overnight leg depends on the following close, rather than valuing the sale at the open plus the cash distribution. In the SPY training backtest, using opening proceeds plus distributions changes the always-overnight annual return from 10.2598% to 10.2556%, about 0.004 percentage points a year. The return formulas and reported results here retain the multiplicative convention.', "",
           md_table(counts.rename_axis("sample")), "",
           "## Checks", "",
           "Largest errors in (1 + overnight)(1 + intraday) = 1 + ret, in the compounded version per sample, and in "
           "overnight against open / previous close on days with no dividend or split (CRSP rounds `ret` to 6 "
           "decimals, so about 5e-7 is expected):", "",
           md_table(checks(df), "{:.2e}"), "",
           "Hand checks on ex-dividend and split days:", "",
           md_table(hand_checks(df), "{:.5f}"), "",
           "Mean rf by calendar days covered (1 is a weekday, 3 a weekend):", "",
           md_table(weekend.rename_axis("days").to_frame(), "{:.3f}"), ""]
    write_report("step3_returns.md", out)
    return df

if __name__ == "__main__":
    report(*sys.argv[1:2])
