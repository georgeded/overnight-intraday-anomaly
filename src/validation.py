# Step 7: run the step 6 strategies on validation (2013-2018) and pick one signal
#
#     python src/validation.py
#
# Rule fixed before the run: best Sharpe at 1 bp averaged over the three ETFs,
# ties at two decimals go to the signal that trades less

import sys

import numpy as np
import pandas as pd

from backtest import SETUP, TICKERS, backtest, body, check_engine, load_sample
from checks import md_table
from config import ROOT, SAMPLES
from signals import SIGNALS

SAMPLE = "validation"
SELECT_COST = "1 bp"


# Apply the fixed rule, returns the signal and the ranking
def select(perf):
    p = perf[(perf["cost"] == SELECT_COST) & perf["strategy"].str.startswith("on_sig")]
    per_etf = p.pivot(index="strategy", columns="ticker", values="sharpe")[TICKERS]
    trades = p.groupby("strategy")["trades_per_yr"].mean()

    tab = per_etf.assign(mean_sharpe=per_etf.mean(axis=1), mean_trades_per_yr=trades)
    tab["mean_sharpe_2dp"] = tab["mean_sharpe"].round(2)
    tab = tab.sort_values(["mean_sharpe_2dp", "mean_trades_per_yr"], ascending=[False, True])
    tab["rank"] = np.arange(1, len(tab) + 1)

    chosen = tab.index[0].removeprefix("on_")
    return chosen, tab.rename_axis("strategy").reset_index()


# Sharpe at 1 bp in train and validation side by side
def train_vs_validation(perf_train, perf_val):
    rows = []
    for name, p in [("train", perf_train), ("validation", perf_val)]:
        q = p[p["cost"] == SELECT_COST].pivot(index="strategy", columns="ticker", values="sharpe")[TICKERS]
        q.columns = [f"{t} {name}" for t in TICKERS]
        rows.append(q)

    tab = pd.concat(rows, axis=1)
    order = ["buy_hold", "intraday", "overnight"] + [f"on_{s}" for s in SIGNALS]
    return tab.loc[order, [f"{t} {n}" for t in TICKERS for n in ["train", "validation"]]].rename_axis("strategy")


NOTES = """## What validation says (yfinance snapshot)

- **The pick is close.** `sig_a` wins with a mean Sharpe of 0.518 against 0.507 for `sig_b` at 1 bp (0.52 vs 0.51
  at two decimals, so not a tie under the rule). The ranking would flip on small changes, so the choice says
  little about which signal is genuinely better.
- **The chosen signal is not consistent across ETFs.** `sig_a` beats always-overnight on Sharpe at 1 bp for SPY
  (0.53 vs 0.41) and IWM (0.74 vs 0.39) but not QQQ (0.28 vs 0.82). Against random nights it sits at the
  82nd (SPY), 22nd (QQQ) and 96th (IWM) percentile on annual return.
- **Validation looks better for the signals than train did.** In train (step 6) every signal was at or below the
  placebo median; in 2013-2018 several are above it, mostly for IWM. With five candidates, three ETFs and one
  six-year sample, some of this is expected by chance; the test period decides.
- **Nothing beats buy-and-hold in 2013-2018.** It was a strong, calm bull market: buy-and-hold made 9.5-16.7% a
  year with Sharpe 0.61-1.01, and every overnight strategy is below it even at zero cost (breakeven vs
  buy-and-hold is `-` throughout). Against cash, always-overnight breaks even at 1.6-2.5 bp per trade and `sig_a`
  at 1.8-2.8 bp, because it trades less than half as often.
- **Always-intraday** loses money at 1 bp on all three ETFs, as in train.
- The Corwin-Schultz estimate (10-16 bp one-way on average) is still far above the real post-2001 spread of these
  ETFs; see step 6.
"""


def report(source="yfinance"):
    ret, sig = load_sample(source, SAMPLE)
    perf, be, plc, win, spread_tab = backtest(source, SAMPLE)
    perf_train = backtest(source, "train")[0]
    eng = check_engine(ret, sig, SAMPLE)
    chosen, ranking = select(perf)
    a, b = SAMPLES[SAMPLE]

    out = [f"# Step 7: validation ({source}, {a[:4]}-{b[:4]})", "",
           f"Generated by `python src/validation.py {source}`. The step 6 engine and strategies are run unchanged on "
           f"validation rows ({a} to {b}). Data after {b} is never loaded (asserted in `backtest.load_sample`). "
           "Earlier rows are used only to warm up the backward-looking spread estimate.", "",
           "## Chosen signal", "",
           f"**`{chosen}`**, now frozen in `src/config.py` as `CHOSEN_SIGNAL`.", "",
           "Rule, fixed before the run: highest Sharpe ratio at 1 bp per trade, averaged over SPY, QQQ and IWM "
           "(so one signal for all three ETFs); averages equal to two decimals are a tie, broken by fewer trades "
           "per year.", "",
           md_table(ranking, "{:.3f}"), "",
           "Sharpe at 1 bp per trade, train (step 6) vs validation, for context:", "",
           md_table(train_vs_validation(perf_train, perf), "{:.2f}"), ""]
    out += SETUP
    out += ["Every signal is defined throughout validation, so each window is the whole 2013-2018 period.", ""]
    out += body(perf, be, plc, win, spread_tab, eng)
    out += [NOTES]

    p = ROOT / "reports" / "step7_validation.md"
    p.write_text("\n".join(out))
    print(f"wrote {p.relative_to(ROOT)}; chosen signal: {chosen}")
    return chosen, ranking, perf, be, plc


if __name__ == "__main__":
    report(sys.argv[1] if len(sys.argv) > 1 else "yfinance")
