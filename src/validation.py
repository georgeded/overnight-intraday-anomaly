# Step 7: validation backtest and signal choice

import sys

import numpy as np
import pandas as pd

from backtest import TICKERS, backtest, body, check_engine, load_sample
from checks import md_table
from config import ROOT, SAMPLES

SELECT_COST = "1 bp"

# Best Sharpe at 1 bp averaged over the three ETFs, ties at two decimals go to fewer trades
def select(perf):
    p = perf[(perf["cost"] == SELECT_COST) & perf["strategy"].str.startswith("on_sig")]
    tab = p.pivot(index="strategy", columns="ticker", values="sharpe")[TICKERS]
    tab = tab.assign(mean_sharpe=tab.mean(axis=1), mean_trades_per_yr=p.groupby("strategy")["trades_per_yr"].mean())
    tab = tab.assign(rounded=tab["mean_sharpe"].round(2)).sort_values(["rounded", "mean_trades_per_yr"], ascending=[False, True])
    tab["rank"] = np.arange(1, len(tab) + 1)
    return tab.index[0].removeprefix("on_"), tab.drop(columns="rounded").reset_index()

def report(source="crsp"):
    ret, sig = load_sample(source, "validation")
    perf, be, plc, win, _ = backtest(source, "validation")
    perf_train = backtest(source, "train")[0]
    chosen, ranking = select(perf)

    sharpe = pd.concat({s: p[p["cost"] == SELECT_COST].pivot(index="strategy", columns="ticker", values="sharpe")[TICKERS]
                        for s, p in [("train", perf_train), ("validation", perf)]}, axis=1)
    sharpe.columns = [f"{t} {s}" for s, t in sharpe.columns]
    a, b = SAMPLES["validation"]

    out = [f"# Step 7: validation ({source}, {a[:4]}-{b[:4]})", "",
           f"Generated by `python src/validation.py {source}`. The step 6 engine runs unchanged on {a} to {b}.", "",
           f"## Chosen signal: `{chosen}`", "",
           "Rule fixed before the run: best Sharpe at 1 bp per trade averaged over SPY, QQQ and IWM, ties at two "
           "decimals go to the signal that trades less.", "",
           md_table(ranking, "{:.3f}"), "",
           "Sharpe at 1 bp, train vs validation:", "",
           md_table(sharpe.rename_axis("strategy"), "{:.2f}"), "",
           "## Validation window", ""]
    out += body(perf, be, plc, win, check_engine(ret, sig, "validation"))

    p = ROOT / "reports" / "step7_validation.md"
    p.write_text("\n".join(out))
    print(f"wrote {p.relative_to(ROOT)}, chosen signal: {chosen}")
    return chosen

if __name__ == "__main__":
    report(sys.argv[1] if len(sys.argv) > 1 else "crsp")
